#!/usr/bin/env node
'use strict';
/**
 * Build-time generator for the NovaLink Live endpoint.
 *
 * Reads `process.env.NOVALINK_LIVE_URL` at packaging time and writes
 * `electron/services/novalink/liveConfig.generated.js`, a tiny CommonJS module
 * the main process requires at boot. This is how a downloaded-and-installed
 * NovaCode finds the messaging backend without ever asking the user for a URL.
 *
 * Contract with the spec:
 *   - Development (NODE_ENV!=='production'): empty URL is allowed; the client
 *     boots unconfigured and the developer sets the URL from the diagnostics
 *     panel or the env. This keeps `npm run dev` usable against a laptop
 *     link-server on 127.0.0.1.
 *   - Production, LAN-first: an empty URL is now a valid packaged state. A
 *     download ships with no cloud endpoint baked in; NovaLink finds a host on
 *     the local network at runtime (electron/services/novalink/lanDiscovery.js)
 *     and points the Live client at it. This is what makes the installer work
 *     with no Render / no paid hosting.
 *   - Production, explicit URL: a *non-empty* value that is malformed, a
 *     placeholder, or plain http is still a hard failure. We never ship a
 *     broken or embarrassing URL. Acceptance test #11 ("no placeholder URLs in
 *     production builds") is enforced here.
 *
 * Not a runtime module. Do not require this from the app; require
 * `electron/services/novalink/liveConfig.js` instead.
 */
const fs = require('node:fs');
const path = require('node:path');

const OUT_DIR = path.join(__dirname, '..', 'electron', 'services', 'novalink');
const OUT_FILE = path.join(OUT_DIR, 'liveConfig.generated.js');

// Anything matching these looks like a tutorial leftover and is never a real
// host. Kept narrow: production hosts like `link.novacode.app` do not match.
const PLACEHOLDER_PATTERNS = [
  /(^|\/\/)link\.example\.com/i,
  /(^|\/\/)example\.(com|org|net)/i,
  /(^|\/\/)localhost(:\d+)?(\/|$)/i,
  /(^|\/\/)127\.0\.0\.1(:\d+)?(\/|$)/i,
  /(^|\/\/)0\.0\.0\.0(:\d+)?(\/|$)/i,
  /(^|\/\/)\[::1\](:\d+)?(\/|$)/i,
  /(^|\/\/)your\.host\//i,
  /(^|\/\/)change-me/i,
];

function classify(raw) {
  const value = typeof raw === 'string' ? raw.trim() : '';
  if (!value) return { ok: false, reason: 'empty' };
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    return { ok: false, reason: 'malformed', value };
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    return { ok: false, reason: 'protocol', value, protocol: parsed.protocol };
  }
  return { ok: true, value: parsed.toString(), protocol: parsed.protocol, host: parsed.host };
}

function main() {
  const raw = process.env.NOVALINK_LIVE_URL || '';
  const isProduction = process.env.NODE_ENV === 'production' || process.env.NOVA_PACK === '1';
  const verdict = classify(raw);

  // LAN-first: an empty URL is a valid packaged state (see the header). Only a
  // non-empty value that fails to classify is rejected in production.
  if (!verdict.ok && isProduction && verdict.reason !== 'empty') {
    throw new Error(`NOVALINK_LIVE_URL is not a valid absolute http(s) URL: "${verdict.value || raw}".`);
  }
  if (verdict.ok && isProduction) {
    const hit = PLACEHOLDER_PATTERNS.find((pattern) => pattern.test(verdict.value));
    if (hit) {
      throw new Error(`NOVALINK_LIVE_URL looks like a placeholder ("${verdict.value}"). Production builds must point at a real deployed host.`);
    }
    if (verdict.protocol !== 'https:') {
      throw new Error(`Production builds must use https for NOVALINK_LIVE_URL (got "${verdict.value}").`);
    }
  }

  if (!fs.existsSync(OUT_DIR)) {
    fs.mkdirSync(OUT_DIR, { recursive: true });
  }
  const exported = verdict.ok ? verdict.value : '';
  const banner = [
    '// GENERATED by scripts/generate-live-config.js — do not edit by hand.',
    `// Built at ${new Date().toISOString()} on host ${require('node:os').hostname()}.`,
    `// NODE_ENV=${process.env.NODE_ENV || 'unset'} NOVA_PACK=${process.env.NOVA_PACK || 'unset'}`,
    '',
  ].join('\n');
  const body = `'use strict';\n${banner}module.exports = { baseUrl: ${JSON.stringify(exported)} };\n`;
  fs.writeFileSync(OUT_FILE, body, 'utf8');
  const label = exported || '(unconfigured — LAN discovery will configure it at runtime)';
  process.stdout.write(`liveConfig.generated.js written. baseUrl = ${label}\n`);
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exit(1);
  }
}

module.exports = { main, classify, PLACEHOLDER_PATTERNS };
